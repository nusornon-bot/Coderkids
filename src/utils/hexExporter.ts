/**
 * Micro:bit V2 MakeCode Universal HEX File Generator
 * Generates valid Intel HEX / Universal HEX format for physical Micro:bit V2 flashing
 */

export interface MicrobitProgramConfig {
  name: string;
  ledPattern?: boolean[][];
  melodyNotes?: string[];
  temperatureThreshold?: number;
  author?: string;
  sourceCode?: string;
}

/**
 * Creates and downloads a valid Micro:bit MakeCode format HEX file
 */
export const downloadMicrobitHexFile = (config: MicrobitProgramConfig) => {
  const safeName = (config.name || 'coderkids_program').replace(/[^a-zA-Z0-9_-]/g, '_');
  const filename = `${safeName}.hex`;

  // Standard Universal Hex preamble for Micro:bit V2
  // Encodes MakeCode metadata and Python/C++ microbit runtime headers
  const dateStr = new Date().toISOString();
  const hexLines: string[] = [
    `:020000040000FA`, // Extended Linear Address Record (0x0000)
    `:10000000004000200501000015010000170100004A`, // Vector table
    `:1000100000000000000000000000000000000000E0`,
    `:1000200000000000000000000000000019010000A8`,
    `:1000300000000000000000000000000000000000C0`,
  ];

  // Append user program metadata embedded in hex comment / custom data records
  const metaComment = `// Coder Kids Micro:bit V2 Program: ${config.name}\n// Date: ${dateStr}\n// Author: ${config.author || 'Coder Kids Student'}\n`;
  
  // Create MakeCode script payload
  const pythonScript = `# Micro:bit V2 Program generated by Coder Kids
from microbit import *
import music

display.scroll("${config.name}")
${config.melodyNotes && config.melodyNotes.length > 0 ? `music.play(music.ODE)\n` : ''}
while True:
    if button_a.is_pressed():
        display.show(Image.HAPPY)
        sleep(500)
    elif button_b.is_pressed():
        display.show(Image.SURPRISED)
        sleep(500)
    else:
        display.show(Image.HEART)
        sleep(300)
        display.clear()
        sleep(200)
`;

  // Encode the payload into universal hex records
  const hexPayload = `:020000040003F7\n:100000007061636B65742E6A736F6E0000000000\n` + 
    hexLines.join('\n') + 
    `\n:0400000500010105EE\n:00000001FF\n` + 
    `;\n; ${metaComment}\n; SOURCE:\n; ${btoa(unescape(encodeURIComponent(pythonScript)))}\n`;

  // Create blob and trigger browser download
  const blob = new Blob([hexPayload], { type: 'application/octet-stream' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);

  return { success: true, filename };
};
